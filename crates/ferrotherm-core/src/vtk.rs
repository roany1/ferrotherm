//! VTK XML RectilinearGrid (.vtr) output, readable by ParaView and VisIt,
//! plus a .pvd collection for transient series.

use crate::model::{Model, Owner};
use crate::simulate::Snapshot;
use std::fmt::Write as _;

fn push_array(out: &mut String, name: &str, ty: &str, vals: impl Iterator<Item = String>) {
    let _ = writeln!(
        out,
        "        <DataArray type=\"{ty}\" Name=\"{name}\" format=\"ascii\">"
    );
    let mut line = String::new();
    for (i, v) in vals.enumerate() {
        line.push_str(&v);
        line.push(' ');
        if i % 8 == 7 {
            out.push_str("          ");
            out.push_str(line.trim_end());
            out.push('\n');
            line.clear();
        }
    }
    if !line.is_empty() {
        out.push_str("          ");
        out.push_str(line.trim_end());
        out.push('\n');
    }
    out.push_str("        </DataArray>\n");
}

/// Serialise one snapshot as a .vtr document. Coordinates are written in mm.
pub fn vtr(m: &Model, s: &Snapshot) -> String {
    let n = m.grid.n();
    let mut out = String::new();
    out.push_str("<?xml version=\"1.0\"?>\n");
    out.push_str("<!-- Generated by FerroTherm (author: Roany Romano) -->\n");
    out.push_str(
        "<VTKFile type=\"RectilinearGrid\" version=\"0.1\" byte_order=\"LittleEndian\">\n",
    );
    let ext = format!("0 {} 0 {} 0 {}", n[0], n[1], n[2]);
    let _ = writeln!(out, "  <RectilinearGrid WholeExtent=\"{ext}\">");
    let _ = writeln!(out, "    <Piece Extent=\"{ext}\">");
    out.push_str("      <CellData Scalars=\"temperature_C\">\n");
    push_array(
        &mut out,
        "temperature_C",
        "Float64",
        s.t[..m.ncells].iter().map(|v| format!("{v:.6}")),
    );
    push_array(
        &mut out,
        "material_id",
        "Int32",
        m.cell_material.iter().map(|v| v.to_string()),
    );
    push_array(
        &mut out,
        "owner",
        "Int32",
        m.owner.iter().map(|o| match o {
            Owner::Fill => "-1".to_string(),
            Owner::Block(b) => b.to_string(),
            Owner::Component(c) => (10_000 + c).to_string(),
        }),
    );
    push_array(
        &mut out,
        "power_density_W_m3",
        "Float64",
        (0..m.ncells).map(|c| format!("{:.6e}", m.source[c] / m.grid.volume(c))),
    );
    push_array(
        &mut out,
        "k_x",
        "Float64",
        m.k.iter().map(|k| format!("{:.6e}", k[0])),
    );
    push_array(
        &mut out,
        "k_z",
        "Float64",
        m.k.iter().map(|k| format!("{:.6e}", k[2])),
    );
    out.push_str("      </CellData>\n      <Coordinates>\n");
    for (a, name) in ["x_mm", "y_mm", "z_mm"].iter().enumerate() {
        push_array(
            &mut out,
            name,
            "Float64",
            m.grid.nodes[a].iter().map(|v| format!("{:.9}", v * 1e3)),
        );
    }
    out.push_str("      </Coordinates>\n    </Piece>\n  </RectilinearGrid>\n</VTKFile>\n");
    out
}

/// ParaView collection file referencing `(time, file name)` pairs.
pub fn pvd(entries: &[(f64, String)]) -> String {
    let mut out = String::from(
        "<?xml version=\"1.0\"?>\n<VTKFile type=\"Collection\" version=\"0.1\">\n  <Collection>\n",
    );
    for (t, f) in entries {
        let _ = writeln!(
            out,
            "    <DataSet timestep=\"{t}\" part=\"0\" file=\"{f}\"/>"
        );
    }
    out.push_str("  </Collection>\n</VTKFile>\n");
    out
}

/// Junction temperature history as CSV.
pub fn junction_csv(m: &Model, hist: &[(f64, Vec<f64>)]) -> String {
    let mut out = String::from("time_s");
    for c in &m.components {
        out.push_str(&format!(",Tj_{}_C", c.name.replace(',', "_")));
    }
    out.push('\n');
    for (t, v) in hist {
        out.push_str(&format!("{t}"));
        for x in v {
            out.push_str(&format!(",{x:.6}"));
        }
        out.push('\n');
    }
    out
}
